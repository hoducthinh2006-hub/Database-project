-- khoa hoc, danh gia, bai hoc, dang ky

create table KhoaHoc(
MaKH int primary key,
TenKH varchar(50) not null,
TrangThai enum('DangMo', 'DaHoanThanh', 'DaHuy') not null default 'DangMo',
ThoiLuong enum('3Thang', '6Thang', '1Nam', 'VoThoiHan') not null,
NgayTao date not null default(current_date),
MoTa text,
HocPhi int not null check(HocPhi >= 0),
LinhVuc varchar(50) not null
);

create table DanhGia(
MaDG int primary key,
MaHV int not null,
foreign key(MaHV) references HocVien(MaHV),
MaKH int not null,
foreign key(MaKH) references KhoaHoc(MaKH),
NgayDG date not null default(current_date),
NhanXet text
);

create table DangKy(
MaDK int primary key,
MaHV int not null,
foreign key(MaHV) references HocVien(MaHV),
MaKH int not null,
foreign key(MaKH) references KhoaHoc(MaKH),
NgayHuy date,
NgayDangKy date not null default(current_date)
);

create table BaiHoc(
MaBH int primary key,
MaKH int not null,
foreign key(MaKH) references KhoaHoc(MaKH),
TenBH varchar(50) not null,
VideoBaiGiang varchar(50) not null,
ThucHanh varchar(50),
ThoiLuong int not null check(ThoiLuong > 0),
GiaoTrinh varchar(50) not null
);









































































































































































































































































































































































































































































































































































































































