UNION ALL SELECT 'Khóa học', COUNT(*) FROM KHOA_HOC UNION ALL SELECT 'Bài học', COUNT(*) FROM BAI_HOC
UNION ALL SELECT 'Bài kiểm tra', COUNT(*) FROM BAI_KIEM_TRA UNION ALL SELECT 'Đăng ký', COUNT(*) FROM DANG_KY
UNION ALL SELECT 'Lịch sử học tập', COUNT(*) FROM LICH_SU_HOC_TAP UNION ALL SELECT 'Kết quả', COUNT(*) FROM KET_QUA
UNION ALL SELECT 'Thanh toán', COUNT(*) FROM THANH_TOAN UNION ALL SELECT 'Chứng chỉ', COUNT(*) FROM CHUNG_CHI
UNION ALL SELECT 'Đánh giá', COUNT(*) FROM DANH_GIA;

